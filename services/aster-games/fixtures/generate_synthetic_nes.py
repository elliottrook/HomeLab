#!/usr/bin/env python3
"""Generate a deterministic, original NES fixture and matching Logiqx DAT."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import zlib


TITLE = "Aster Infrastructure Test (World) (Homebrew)"
FILENAME = TITLE + ".nes"


def build_rom() -> tuple[bytes, bytes]:
    header = b"NES\x1a" + bytes((1, 1, 0, 0)) + bytes(8)
    prg = bytearray([0xEA] * 16384)
    prg[:8] = bytes((0x78, 0xD8, 0xA2, 0xFF, 0x9A, 0x4C, 0x05, 0x80))
    prg[-6:] = bytes((0x05, 0x80, 0x00, 0x80, 0x05, 0x80))
    chr_data = bytes(8192)
    body = bytes(prg) + chr_data
    return header + body, body


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-dir", required=True, type=Path)
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)

    rom, body = build_rom()
    rom_path = args.output_dir / FILENAME
    dat_path = args.output_dir / "aster-infrastructure-test.dat"
    manifest_path = args.output_dir / "fixture-manifest.json"
    rom_path.write_bytes(rom)

    crc = f"{zlib.crc32(body) & 0xFFFFFFFF:08x}"
    md5 = hashlib.md5(body, usedforsecurity=False).hexdigest()
    sha1 = hashlib.sha1(body, usedforsecurity=False).hexdigest()
    dat_path.write_text(
        "<?xml version=\"1.0\"?>\n"
        "<datafile>\n"
        "  <header><name>Aster Infrastructure Test</name>"
        "<version>1</version></header>\n"
        f"  <game name=\"{TITLE}\">\n"
        f"    <description>{TITLE}</description>\n"
        f"    <rom name=\"{FILENAME}\" size=\"{len(body)}\" "
        f"crc=\"{crc}\" md5=\"{md5}\" sha1=\"{sha1}\"/>\n"
        "  </game>\n"
        "</datafile>\n",
        encoding="utf-8",
    )
    manifest_path.write_text(
        json.dumps(
            {
                "license": "CC0-1.0",
                "origin": "deterministically generated by this repository",
                "rom": FILENAME,
                "rom_sha256": hashlib.sha256(rom).hexdigest(),
                "dat": dat_path.name,
                "dat_body_sha1": sha1,
                "dat_body_size": len(body),
            },
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )
    print(json.dumps({"generated": True, "license": "CC0-1.0", "files": 3}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
