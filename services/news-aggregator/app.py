def _parse_source_line(line: str) -> tuple[str, str | None]:
    """"Name | URL" if both given, or just a bare name/URL on its own."""
    if "|" in line:
        name, _, url = line.partition("|")
        return name.strip(), url.strip() or None
    return line.strip(), None


