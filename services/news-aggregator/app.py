"""Private, internal-only reading UI. Two views share one Flask app:

/ (breaking news) -- unchanged from Phase 1: renders clusters newest-first,
a cluster summary (multi-outlet) or a single item's own RSS description
(single-outlet), with outlet-level bias ratings shown when available.

/digest (Phase 2) -- twice-daily curated digest: only multi-outlet
clusters, each with an abridged multi-source summary and deviation notes
(what one outlet says that others don't), styled as a card with a hero
image when the source feed provided one, or a plain outlet-badge header
when it didn't (most feeds don't -- see the Phase 2 project doc).

/settings (Phase 2) -- a queue, not a write path: requests land in
source_requests and are never auto-added to feeds.json. Every feed added
to this project so far has needed live verification first (2 of the
original 9 candidate URLs were wrong; AP News turned out to have no
accessible feed at all) -- a submitted URL gets the same diligence, not a
shortcut around it.

The required non-authoritative caveat is always visible on the two
reading views."""

