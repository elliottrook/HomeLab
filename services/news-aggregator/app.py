def _outlets_for_cluster(conn: sqlite3.Connection, cluster_id: int, items: list[sqlite3.Row]) -> list[dict]:
    outlets = []
    seen_feed_ids = set()
    for item in items:
        # A cluster can contain more than one item from the same feed_id
        # (e.g. a source cross-posting one story under several URLs, now
        # merged by cluster.py's same-outlet matching) -- show that
        # outlet's badge once, not once per duplicate row.
        if item["feed_id"] in seen_feed_ids:
            continue
        seen_feed_ids.add(item["feed_id"])
        rating = conn.execute(
            "SELECT rating_label, source_name, notes FROM outlet_ratings WHERE feed_id = ?",
            (item["feed_id"],),
        ).fetchone()
        outlets.append({
            "feed_id": item["feed_id"],
            "link": item["link"],
            "rating": rating["rating_label"] if rating else None,
            "rating_source": rating["source_name"] if rating else None,
            "rating_notes": rating["notes"] if rating else None,
        })
    return outlets


def get_clusters(limit: int = 40):
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    cluster_ids = [
        row["cluster_id"]
        for row in conn.execute(
            "SELECT cluster_id, MAX(fetched_at) AS latest FROM feed_items "
            "WHERE cluster_id IS NOT NULL GROUP BY cluster_id "
            "ORDER BY latest DESC LIMIT ?",
            (limit,),
        )
    ]
    clusters = []
    for cid in cluster_ids:
        items = conn.execute(
            "SELECT id, feed_id, title, link, summary FROM feed_items WHERE cluster_id = ?",
            (cid,),
        ).fetchall()
        if not items:
            continue
        summary_row = conn.execute(
            "SELECT summary FROM cluster_summaries WHERE cluster_id = ?", (cid,)
        ).fetchone()
        outlets = _outlets_for_cluster(conn, cid, items)
        lang_note = None
        for item in items:
            note_row = conn.execute(
                "SELECT note FROM item_language_notes WHERE item_id = ? AND note IS NOT NULL",
                (item["id"],),
            ).fetchone()
            if note_row and not lang_note:
                lang_note = note_row["note"]
        clusters.append({
            "headline": items[0]["title"],
            "summary": summary_row["summary"] if summary_row else None,
            "raw_summary": items[0]["summary"],
            "outlets": outlets,
            "lang_note": lang_note,
        })
    conn.close()
    return clusters


def get_digest_entries(limit: int = 21):
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    latest_run = conn.execute("SELECT MAX(digest_run) AS run FROM digest_entries").fetchone()["run"]
    previous_run = conn.execute(
        "SELECT MAX(digest_run) AS run FROM digest_entries WHERE digest_run < ?",
        (latest_run,),
    ).fetchone()["run"] if latest_run else None
    digest_columns = {row[1] for row in conn.execute("PRAGMA table_info(digest_entries)")}
    optional_image_columns = ", image_credit, image_source_url" if {"image_credit", "image_source_url"}.issubset(digest_columns) else ""
    rows = conn.execute(
        "SELECT cluster_id, abridged_summary, deviation_notes, image_url" + optional_image_columns + " "
        "FROM digest_entries WHERE digest_run = ? ORDER BY generated_at DESC LIMIT ?",
        (latest_run, limit * 2),
    ).fetchall()
    previous_titles = []
    if previous_run:
        previous_titles = [
            row["title"] for row in conn.execute(
                "SELECT fi.title FROM feed_items fi "
                "JOIN (SELECT DISTINCT cluster_id FROM digest_entries WHERE digest_run = ?) old "
                "ON old.cluster_id = fi.cluster_id",
                (previous_run,),
            ).fetchall()
        ]
    entries = []
    for de in rows:
        cid = de["cluster_id"]
        items = conn.execute(
            "SELECT id, feed_id, title, link FROM feed_items WHERE cluster_id = ?",
            (cid,),
        ).fetchall()
        items = coherent_event(items)
        if not items:
            continue
        if len({item["feed_id"] for item in items}) < 2:
            continue
        entries.append({
            "title": items[0]["title"],
            "headline": items[0]["title"],
            "summary": de["abridged_summary"],
            "dedupe_text": de["abridged_summary"],
            "deviation_notes": de["deviation_notes"],
            "image_url": de["image_url"],
            "image_credit": de["image_credit"] if "image_credit" in de.keys() else None,
            "image_source_url": de["image_source_url"] if "image_source_url" in de.keys() else None,
            "outlets": _outlets_for_cluster(conn, cid, items),
        })
    entries = [
        entry for entry in entries
        if not any(repeat_story(entry["headline"], old_title) for old_title in previous_titles)
    ]
    entries = dedupe_titles(entries, text_key="dedupe_text")[:limit]
    conn.close()
    return entries


def get_digest_updated_at() -> str:
    """Return the latest digest generation time in the established BC local time."""
    conn = sqlite3.connect(DB_PATH)
    row = conn.execute("SELECT MAX(generated_at) AS generated FROM digest_entries").fetchone()
    conn.close()
    if not row or not row[0]:
        return "Waiting for the first digest run"
    try:
        generated = datetime.fromisoformat(row[0].replace("Z", "+00:00")) + BC_OFFSET
        return f"Updated {generated.strftime('%b %-d, %Y at %-I:%M %p')}"
    except ValueError:
        return "Updated from the latest digest run"


