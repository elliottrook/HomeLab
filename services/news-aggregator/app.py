@app.route("/settings", methods=["GET", "POST"])
def settings():
    flash = None
    if request.method == "POST":
        category_choice = (request.form.get("category_choice") or "").strip()
        is_new = category_choice == "__new__"
        category = (request.form.get("new_category") or "").strip() if is_new else category_choice
        note = (request.form.get("note") or "").strip() or None
        lines = [ln.strip() for ln in (request.form.get("sources") or "").splitlines() if ln.strip()]

        if not category:
            flash = "No category given -- request not saved. Pick an existing one or name a new one."
        elif not lines:
            flash = "No sources given -- request not saved."
        else:
            conn = sqlite3.connect(DB_PATH)
            now = datetime.now(timezone.utc).isoformat()
            for line in lines:
                name, url = _parse_source_line(line)
                if not name:
                    continue
                conn.execute(
                    "INSERT INTO source_requests "
                    "(requested_name, requested_url, category, is_new_category, note, status, requested_at) "
                    "VALUES (?, ?, ?, ?, ?, 'pending', ?)",
                    (name, url, category, int(is_new), note, now),
                )
            conn.commit()
            conn.close()
            # Redirect (POST/redirect/GET) so refreshing the settings page
            # never resubmits the form.
            return redirect(url_for("settings", saved=len(lines)))

    if request.args.get("saved"):
        flash = f"{request.args['saved']} source request(s) queued for review."

    return render_template_string(
        TEMPLATE_SETTINGS,
        categories=get_known_categories(),
        requests=get_pending_requests(),
        flash=flash,
        active_page="settings",
    )


